#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_help_is_the_recovered_file() {
        assert!(LINES[0].contains("Version 1.40"));
        assert!(LINES.iter().any(|line| line.contains("End of Help")));
        assert!(LINES.iter().any(|line| line.contains("CABLE-RS")));
        assert!(LINES.iter().any(|line| line.contains("F8")));
        assert!(LINES.iter().all(|line| !line.contains('\r')));
    }
}
